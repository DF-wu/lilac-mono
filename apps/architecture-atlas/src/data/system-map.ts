type NodeInput = Omit<SystemNodeData, "searchText">;

function nodeData(input: NodeInput): SystemNodeData {
  return {
    ...input,
    searchText: [
      input.label,
      input.eyebrow,
      input.summary,
      ...input.responsibilities,
      ...input.inputs,
      ...input.outputs,
      ...input.technologies,
    ]
      .join(" ")
      .toLocaleLowerCase("zh-Hant"),
  };
}

